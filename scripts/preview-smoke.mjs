import assert from "node:assert/strict";
import { build } from "esbuild";
const result = await build({ entryPoints: ["src/lib/preview-data.ts"], bundle: true, write: false, platform: "node", format: "cjs" });
const module = { exports: {} };
new Function("module", "exports", result.outputFiles[0].text)(module, module.exports);
const { getPreviewDashboard, getPreviewDashboardIssues, previewMembers } = module.exports;
const get = (query = "") => getPreviewDashboard(new URLSearchParams(query));
const initial = get("active=true&sortCol=currentLoad&sortDir=desc");
assert.equal(initial.total, 12);
assert.equal(initial.data.length, 10);
assert.equal(initial.summary.totalOpenIssues, 51);
assert.equal(initial.summary.resolvedLast7Days, 12);
assert.equal(initial.attentionIssues.length, 3);
assert.equal(initial.trends.weeks.length, 4);
assert.equal(initial.trends.weeks[3].resolved, initial.summary.resolvedLast7Days);
assert.deepEqual(initial.trends, get("active=true&page=2").trends);
assert.ok(get("name=nobody").trends.weeks.every((week) => week.created === 0 && week.resolved === 0));
assert.ok(initial.attentionIssues.every((issue) => issue.ageDays > initial.thresholds.staleDays));
assert.deepEqual(initial.attentionIssues, get("active=true&page=2").attentionIssues);
assert.equal(get("active=true&teamId=demo-product").summary.resolvedLast7Days, 4);
assert.equal(get("active=true&name=Sarah").summary.resolvedLast7Days, 1);
assert.equal(get("name=nobody").summary.resolvedLast7Days, 0);
assert.equal(get("repositoryId=missing").summary.resolvedLast7Days, 0);
assert.ok(get("active=true&platform=github").summary.resolvedLast7Days < initial.summary.resolvedLast7Days);
const issuePage = (query) => getPreviewDashboardIssues(new URLSearchParams(query));
assert.equal(issuePage("active=true&issueView=stale").total, initial.summary.staleIssues);
assert.equal(issuePage("active=true&issueView=open").data.length, 20);
assert.equal(issuePage("active=true&issueView=open&issuePage=3").data.length, 11);
assert.equal(issuePage("active=true&issueView=stale&teamId=demo-product").total, get("active=true&teamId=demo-product").summary.staleIssues);
assert.equal(issuePage("active=true&issueView=stale&repositoryId=missing").total, 0);
assert.deepEqual(initial.summary.distribution, { low: 6, medium: 4, high: 2 });
assert.equal(initial.data[0].name, "Aditya Pratama");
assert.equal(initial.teamOverview.length, 3);
assert.equal(get("active=true&page=2").data.length, 2);
assert.equal(get("active=true&teamId=demo-product").total, 4);
assert.equal(get("active=true&name=Sarah").total, 1);
assert.equal(get("active=true&name=Sarah").data[0].currentLoad, 6);
assert.equal(get("active=true&workload=high").total, 2);
assert.equal(get("active=true&workload=high").summary.memberCount, 12);
assert.equal(get("active=true&workload=all").total, 12);
assert.equal(get("active=false").total, 2);
assert.equal(get("name=nobody").total, 0);
assert.equal(get("repositoryId=missing").summary.totalOpenIssues, 0);
assert.ok(get("platform=github").summary.totalOpenIssues < get().summary.totalOpenIssues);
assert.equal(previewMembers.every((m) => m.memberId.startsWith("demo-") && m.avatarUrl === null), true);
console.log("Preview checks passed: sample totals, pagination, sorting, team/name/workload/status/repository/platform filters, and empty results.");
